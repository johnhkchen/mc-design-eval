// Each clan's palette (short material swaps: orange=brown, acacia=spruce, red_sandstone=mud_bricks) expanded into plain
// block-id swaps for the client's placer: every 1.21.1 block the palette rewrites, `minecraft:a=minecraft:b`, so the
// Java port reads the list straight, with no token rules. Written beside the palette as the clan's `swaps`.
//   node src/styles/expand.mjs [style ...]      (default: every style with factions)
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { Assets } from "/Volumes/ext1/swe/repos/minecraft-design/tools/src/assets.mjs";
import { parseSwaps, reskinBlock } from "/Volumes/ext1/swe/repos/minecraft-design/tools/src/reskin.mjs";

const DIR = `${new URL(".", import.meta.url).pathname}../../styles`;
const blocks = (await Assets.open("1.21.1")).blocks(), known = new Set(blocks);
const ids = process.argv.slice(2).length ? process.argv.slice(2) : readdirSync(DIR).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5));
for (const id of ids) {
  const f = `${DIR}/${id}.json`, st = JSON.parse(readFileSync(f, "utf8"));
  if (!st.factions?.clans) continue;
  for (const [k, c] of Object.entries(st.factions.clans)) {
    const sw = parseSwaps(c.palette);
    c.swaps = blocks.flatMap((b) => { const t = reskinBlock(b, sw, known); return t && t !== b ? [`minecraft:${b}=minecraft:${t}`] : []; });
    console.log(`${id}/${k}: ${c.palette.length} palette entries -> ${c.swaps.length} block swaps`);
  }
  st.factions.about = st.factions.about.replace(/ Each clan's `swaps`.*$/, "") + " Each clan's `swaps` is its palette expanded to plain block ids for 1.21.1 (generated by src/styles/expand.mjs: read these, not the palette).";
  writeFileSync(f, JSON.stringify(st, null, 2) + "\n");
}
