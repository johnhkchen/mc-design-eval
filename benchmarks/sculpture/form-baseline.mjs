// Form-fidelity baseline generator (T-043-01, story S-043, epic E-15).
//
// Runs the silhouette IoU metric (src/form/form-fidelity.mjs) over every committed E-13 render/concept
// pair and writes a per-subject baseline — the "before" the rest of E-15 (region-lock + revision loop)
// hill-climbs against. Deterministic: pairs are discovered sorted, no clock/RNG touches the committed
// output. Run with:  node benchmarks/sculpture/form-baseline.mjs
//
// Mirrors codesign-ab.mjs (the E-14 sibling): a generator .mjs writing a committed .json + .md.

import { readFileSync, readdirSync, existsSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { formFidelityFromPair, FORM_DEFAULTS, FORM_FIDELITY_SCHEMA } from "../../src/form/form-fidelity.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const RUNS_DIR = join(HERE, "runs");
const GENERATED_FROM = "benchmarks/sculpture/runs/*/{render-3q.png,concept.png}";

/** Subject label for a run dir: prefer summary.json `.term`, fall back to the dir name. */
function subjectOf(dir, name) {
  const summaryPath = join(dir, "summary.json");
  if (existsSync(summaryPath)) {
    try {
      const s = JSON.parse(readFileSync(summaryPath, "utf8"));
      if (typeof s.term === "string" && s.term.trim()) return s.term.trim();
    } catch {
      /* fall through to dir-name */
    }
  }
  return name.replace(/^\d+-vConcept-/, "").replace(/-/g, " ");
}

/** Discover run dirs with BOTH a render-3q.png and a concept.png, sorted by name (deterministic). */
function discoverPairs() {
  if (!existsSync(RUNS_DIR)) return [];
  const pairs = [];
  for (const name of readdirSync(RUNS_DIR).sort()) {
    const dir = join(RUNS_DIR, name);
    const render = join(dir, "render-3q.png");
    const concept = join(dir, "concept.png");
    if (existsSync(render) && existsSync(concept)) pairs.push({ name, dir, render, concept });
  }
  return pairs;
}

function mdTable(rows) {
  const head =
    "| run | subject | IoU | render cov | concept cov | render aspect | concept aspect |\n" +
    "|-----|---------|----:|-----------:|------------:|--------------:|---------------:|";
  const body = rows
    .map(
      (r) =>
        `| ${r.run} | ${r.subject} | ${r.iou.toFixed(3)} | ${r.renderCoverage.toFixed(3)} | ` +
        `${r.conceptCoverage.toFixed(3)} | ${r.renderAspect ?? "—"} | ${r.conceptAspect ?? "—"} |`,
    )
    .join("\n");
  return `${head}\n${body}`;
}

async function main() {
  const pairs = discoverPairs();
  if (pairs.length === 0) {
    console.error(`form-baseline: no render/concept pairs under ${RUNS_DIR}`);
    process.exit(1);
  }

  const subjects = [];
  for (const p of pairs) {
    const r = await formFidelityFromPair(p.render, p.concept);
    subjects.push({
      run: p.name,
      subject: subjectOf(p.dir, p.name),
      iou: r.iou,
      renderCoverage: r.render.coverage,
      conceptCoverage: r.concept.coverage,
      renderAspect: r.render.aspect,
      conceptAspect: r.concept.aspect,
    });
    console.log(`${p.name.padEnd(46)} IoU ${r.iou.toFixed(3)}`);
  }

  const ious = subjects.map((s) => s.iou);
  const mean = Math.round((ious.reduce((a, b) => a + b, 0) / ious.length) * 1000) / 1000;
  const sorted = [...subjects].sort((a, b) => a.iou - b.iou);
  const lowest = sorted[0];
  const highest = sorted[sorted.length - 1];

  const json = {
    schema: FORM_FIDELITY_SCHEMA,
    metric: "silhouette-iou",
    grid: FORM_DEFAULTS.grid,
    fit: FORM_DEFAULTS.fit,
    generatedFrom: GENERATED_FROM,
    meanIoU: mean,
    subjects,
  };
  writeFileSync(join(HERE, "form-baseline.json"), JSON.stringify(json, null, 2) + "\n");

  const md = `# Form-fidelity baseline (E-15 "before")

Whole-object silhouette **IoU** between each E-13 build's \`render-3q.png\` (sky-segmented) and its
\`concept.png\` (black-segmented), normalized to a ${FORM_DEFAULTS.grid}×${FORM_DEFAULTS.grid} grid with
\`fit:"${FORM_DEFAULTS.fit}"\` (proportion preserved). Generated by \`form-baseline.mjs\` over
\`${GENERATED_FROM}\`. Schema \`${FORM_FIDELITY_SCHEMA}\`.

**This is the number E-15's surgical revision loop must move up.** It is the form analogue of E-14's
concept↔render Δvalue gate: color got a hill-climb number, form now has one too.

${mdTable(subjects)}

Mean IoU **${mean.toFixed(3)}** · lowest **${lowest.subject}** (${lowest.run}, ${lowest.iou.toFixed(3)})
· highest **${highest.subject}** (${highest.run}, ${highest.iou.toFixed(3)}).

## How to read this — and what it can't see

The IoU is **honestly modest**, and the limits below explain why a "good" build still scores well under 1.
The metric's worth is the **relative Δ between revisions** the loop reads, not the absolute value:

1. **Single 3/4 view** — one side only; the back is invisible (the single-view reconstruction limit
   E-13/E-14 already carry).
2. **Camera mismatch** — the render is exactly \`SCULPTURE_VIEW_3Q\` (azimuth 45°, elevation 30°); the
   concept is only *approximately* 3/4 (Nano-Banana), so the two silhouettes never perfectly register.
3. **Aspect-fit alignment** — we bbox-crop + scale (translation+scale invariant) and **preserve
   proportion**, so a subject elongated in the concept but stubby in the render scores lower — proportion
   *is* form (the koi-S-curve / aortic-arch failure mode). Rotation is *not* corrected (treated as a real
   defect). \`fit:"stretch"\` would discard proportion instead.
4. **Background collateral** — segmentation drops foreground within tolerance of the background color
   (dark-on-black, sky-blue-on-sky); inherited E-10 caveat.
5. **Silhouette ≠ form** — two shapes can share an outline; IoU is necessary, not sufficient. Paired in the
   loop with the color gate, it is the cheap honest number, not a complete form judge.
`;
  writeFileSync(join(HERE, "form-baseline.md"), md);
  console.log(`\nWrote form-baseline.{json,md} · ${subjects.length} subjects · mean IoU ${mean.toFixed(3)}`);
}

main();
