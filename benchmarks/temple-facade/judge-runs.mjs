// Retro-score existing runs with the rubric judge and refresh the gallery. Use to grade
// runs made before the judge existed, or to re-grade after a rubric change.
//   npm run bench:judge                 # score every run that lacks a score
//   npm run bench:judge -- --all        # re-score every run
//   npm run bench:judge -- 003-v2-designdoc   # score specific run dir(s)
//
// LIVE & METERED (one claude -p judge call per run scored).

import { readFileSync, writeFileSync, readdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { judgeRender } from "./judge.mjs";
import { TEMPLE_FACADE_TASK } from "./task.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const RUNS_DIR = join(HERE, "runs");
const README = join(HERE, "README.md");

// Gallery regeneration (kept in sync with run.mjs's copy).
function regenerateReadme() {
  const dirs = existsSync(RUNS_DIR)
    ? readdirSync(RUNS_DIR).filter((d) => existsSync(join(RUNS_DIR, d, "summary.json")))
    : [];
  const summaries = dirs
    .map((d) => JSON.parse(readFileSync(join(RUNS_DIR, d, "summary.json"), "utf8")))
    .sort((a, b) => a.seq - b.seq);
  const usd = (n) => `$${Number(n ?? 0).toFixed(4)}`;
  const dur = (ms) => (ms ? `${Math.round(ms / 1000)}s` : "—");
  const sc = (s) => (s.score && s.score.overall != null ? `${s.score.overall}` : "—");
  const table = [
    "| # | date | approach | score | blocks | tok in/out | $ | wall | note |",
    "|---|------|----------|-------|--------|-----------|---|------|------|",
    ...summaries.map(
      (s) =>
        `| ${s.seq} | ${s.date} | \`${s.approach}\` | ${sc(s)} | ${s.blocks} | ${s.tokensIn}/${s.tokensOut} | ${usd(s.costUsd)} | ${dur(s.durationMs)} | ${s.note || ""} |`,
    ),
  ].join("\n");
  const gallery = summaries
    .map(
      (s) =>
        `### ${String(s.seq).padStart(3, "0")} — \`${s.approach}\` · ${s.date}\n\n` +
        `![temple-facade run ${s.seq}](runs/${s.runId}/render.png)\n\n` +
        `score ${sc(s)}/5 · ${s.blocks} blocks · ${s.tokensIn}/${s.tokensOut} tok · ${usd(s.costUsd)}` +
        (s.note ? `\n\n> ${s.note}` : ""),
    )
    .join("\n\n");
  const body = summaries.length
    ? `${table}\n\n## Gallery\n\n${gallery}`
    : "_(no runs yet)_";
  const block = `<!-- RUNS:START (generated by run.mjs — do not edit by hand) -->\n\n${body}\n\n<!-- RUNS:END -->`;
  writeFileSync(README, readFileSync(README, "utf8").replace(/<!-- RUNS:START[\s\S]*?<!-- RUNS:END -->/, block));
}

const args = process.argv.slice(2);
const all = args.includes("--all");
const only = args.filter((a) => !a.startsWith("--"));

const dirs = readdirSync(RUNS_DIR)
  .filter((d) => existsSync(join(RUNS_DIR, d, "render.png")) && existsSync(join(RUNS_DIR, d, "summary.json")))
  .filter((d) => (only.length ? only.includes(d) : true))
  .sort();

for (const d of dirs) {
  const sumPath = join(RUNS_DIR, d, "summary.json");
  const summary = JSON.parse(readFileSync(sumPath, "utf8"));
  if (summary.score && !all && only.length === 0) {
    console.log(`skip ${d} (already scored ${summary.score.overall}; use --all to re-score)`);
    continue;
  }
  console.log(`judging ${d} ...`);
  const score = await judgeRender({ imagePath: join(RUNS_DIR, d, "render.png"), brief: TEMPLE_FACADE_TASK.goal });
  summary.score = score;
  writeFileSync(sumPath, JSON.stringify(summary, null, 2) + "\n");
  console.log(
    `  ${d}: overall ${score.overall} (prop ${score.proportion} / color ${score.color} / detail ${score.detail} / fidelity ${score.fidelity}) — ${score.notes}`,
  );
}
regenerateReadme();
console.log("done; README gallery updated.");
